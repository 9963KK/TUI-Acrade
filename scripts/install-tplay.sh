#!/bin/sh
# 安装 tplay 命令：在 PATH 中的用户目录生成一个启动脚本，指向本源码仓库的 play.sh。
# 用法：scripts/install-tplay.sh [--uninstall]
# 安装位置默认为 ~/.local/bin，可用 TPLAY_BIN_DIR 指定。
set -e
repo=$(cd -- "$(dirname -- "$0")/.." && pwd)
dir=${TPLAY_BIN_DIR:-"$HOME/.local/bin"}
target="$dir/tplay"
marker="# tplay: generated by TUI Arcade scripts/install-tplay.sh"

ours() { [ -f "$target" ] && grep -qF "$marker" "$target"; }

if [ "$1" = "--uninstall" ]; then
    if ours; then
        rm -f "$target"
        echo "已移除 $target"
    else
        echo "$target 不是本脚本安装的，未做改动。" >&2
    fi
    exit 0
fi

# 不覆盖别的程序安装的同名命令。
if [ -e "$target" ] && ! ours; then
    echo "$target 已存在且不是本脚本安装的，未做改动。" >&2
    exit 1
fi
command -v go >/dev/null 2>&1 || echo "提示：未找到 go，tplay 首次运行时需要 Go 1.26+ 构建平台。" >&2

mkdir -p "$dir"
tmp="$target.tmp.$$"
{
    echo "#!/bin/sh"
    echo "$marker"
    echo "# 启动 TUI Arcade 终端游戏厅；每次启动都按源码构建，改动代码后无需重新安装。"
    printf 'exec "%s/play.sh" "$@"\n' "$repo"
} > "$tmp"
chmod 755 "$tmp"
mv "$tmp" "$target"
echo "已安装 $target -> $repo/play.sh"

case ":$PATH:" in
    *":$dir:"*) echo "现在可以在任意目录运行 tplay。" ;;
    *) echo "注意：$dir 不在 PATH 中，请把它加入 shell 配置后再运行 tplay。" >&2 ;;
esac
